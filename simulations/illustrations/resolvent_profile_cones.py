from __future__ import annotations

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.patches import Polygon, Wedge


BLUE = "tab:blue"
BLACK = "black"


def setup_complex_plane(axis, x_limits, y_limits):
    """Draw a sparse complex plane with arrowed real and imaginary axes."""
    axis.set_xlim(*x_limits)
    axis.set_ylim(*y_limits)
    axis.set_aspect("equal", adjustable="box")
    axis.set_xticks([])
    axis.set_yticks([])
    for spine in axis.spines.values():
        spine.set_visible(False)

    axis.annotate(
        "",
        xy=(x_limits[1], 0.0),
        xytext=(x_limits[0], 0.0),
        arrowprops=dict(arrowstyle="-|>", color=BLACK, linewidth=0.9),
        zorder=5,
    )
    axis.annotate(
        "",
        xy=(0.0, y_limits[1]),
        xytext=(0.0, y_limits[0]),
        arrowprops=dict(arrowstyle="-|>", color=BLACK, linewidth=0.9),
        zorder=5,
    )
    axis.text(
        x_limits[1],
        -0.075 * (y_limits[1] - y_limits[0]),
        r"$\operatorname{Re}$",
        ha="right",
        va="top",
        color=BLACK,
    )
    axis.text(
        0.045 * (x_limits[1] - x_limits[0]),
        y_limits[1],
        r"$\operatorname{Im}$",
        ha="left",
        va="top",
        color=BLACK,
    )
    axis.scatter([0.0], [0.0], s=10, color=BLACK, zorder=7)


def draw_truncated_cone(axis, upper_angle, radius):
    """Shade a cone from angle zero to upper_angle and draw its boundaries."""
    angle_degrees = np.degrees(upper_angle)
    axis.add_patch(
        Wedge(
            (0.0, 0.0),
            radius,
            0.0,
            angle_degrees,
            facecolor=BLACK,
            edgecolor="none",
            alpha=0.065,
            zorder=0,
        )
    )
    for angle in (0.0, upper_angle):
        direction = np.array([np.cos(angle), np.sin(angle)])
        axis.plot(
            [0.0, radius * direction[0]],
            [0.0, radius * direction[1]],
            color=BLACK,
            linewidth=1.35,
            zorder=3,
        )


def draw_resolvent_cone(axis):
    """Left panel: C_z for a spectral parameter close to the positive axis."""
    z_value = 2.0 + 1.0j / 3.0
    boundary_generator = -np.conjugate(z_value)
    upper_angle = np.angle(boundary_generator)
    cone_radius = 2.72

    setup_complex_plane(axis, (-2.75, 2.75), (-0.42, 2.72))
    draw_truncated_cone(axis, upper_angle, cone_radius)

    axis.annotate(
        "",
        xy=(z_value.real, z_value.imag),
        xytext=(0.0, 0.0),
        arrowprops=dict(arrowstyle="-|>", color=BLUE, linewidth=1.8),
        zorder=8,
    )
    axis.scatter(
        [z_value.real],
        [z_value.imag],
        s=31,
        color=BLUE,
        zorder=9,
    )
    axis.text(
        z_value.real + 0.10,
        z_value.imag + 0.10,
        r"$z$",
        color=BLUE,
        ha="left",
        va="bottom",
    )

    axis.scatter([1.0], [0.0], s=22, color=BLACK, zorder=8)
    axis.text(1.0, -0.13, r"$1$", color=BLACK, ha="center", va="top")

    axis.scatter(
        [boundary_generator.real],
        [boundary_generator.imag],
        s=22,
        color=BLACK,
        zorder=8,
    )
    axis.text(
        boundary_generator.real - 0.08,
        boundary_generator.imag + 0.12,
        r"$-\overline{z}$",
        color=BLACK,
        ha="right",
        va="bottom",
    )
    axis.text(
        -0.45,
        1.35,
        r"$\mathcal{C}_z$",
        color=BLACK,
        ha="center",
        va="center",
        fontsize=13,
    )
    axis.set_title(
        r"(a) $\mathcal{C}_z="
        r"\operatorname{cone}\{1,-\overline{z}\}$"
    )


def draw_compact_profile_cone(axis):
    """Right panel: C_K for a disconnected compact set K."""
    # K has two disjoint convex components.  The left component crosses the
    # negative real axis; the right component lies in the upper half-plane.
    ellipse_parameter = np.linspace(0.0, 2.0 * np.pi, 241)
    left_component = np.column_stack(
        (
            -1.40 + 0.52 * np.cos(ellipse_parameter),
            0.38 * np.sin(ellipse_parameter),
        )
    )
    right_component = np.array(
        [
            [0.58, 0.92],
            [1.20, 0.92],
            [1.20, 2.05],
            [0.58, 2.05],
        ]
    )

    # K_+ is obtained by preserving the real part and folding the lower
    # half-plane upward.  The sector itself is generated by -conj(K_+).
    right_component_plus = np.column_stack(
        (right_component[:, 0], right_component[:, 1])
    )
    half_ellipse_parameter = np.linspace(0.0, np.pi, 161)
    left_component_plus = np.column_stack(
        (
            -1.40 + 0.52 * np.cos(half_ellipse_parameter),
            0.38 * np.sin(half_ellipse_parameter),
        )
    )
    right_boundary_generators = np.column_stack(
        (-right_component_plus[:, 0], right_component_plus[:, 1])
    )
    left_boundary_generators = np.column_stack(
        (-left_component_plus[:, 0], left_component_plus[:, 1])
    )
    generator_vertices = np.vstack(
        (right_boundary_generators, left_boundary_generators)
    )
    generator_angles = np.arctan2(
        generator_vertices[:, 1], generator_vertices[:, 0]
    )
    upper_angle = max(np.pi / 3.0, float(np.max(generator_angles)))
    cone_radius = 2.78

    setup_complex_plane(axis, (-2.55, 2.68), (-0.58, 2.78))
    draw_truncated_cone(axis, upper_angle, cone_radius)

    floor_direction = np.array(
        [np.cos(np.pi / 3.0), np.sin(np.pi / 3.0)]
    )
    axis.plot(
        [0.0, cone_radius * floor_direction[0]],
        [0.0, cone_radius * floor_direction[1]],
        color=BLACK,
        linewidth=1.1,
        linestyle=(0, (4, 3)),
        zorder=2,
    )
    axis.scatter(
        [floor_direction[0]],
        [floor_direction[1]],
        s=22,
        color=BLACK,
        zorder=8,
    )
    axis.text(
        floor_direction[0] + 0.07,
        floor_direction[1] + 0.02,
        r"$e^{\mathrm{i}\pi/3}$",
        color=BLACK,
        ha="left",
        va="bottom",
    )

    axis.scatter([1.0], [0.0], s=22, color=BLACK, zorder=8)
    axis.text(1.0, -0.13, r"$1$", color=BLACK, ha="center", va="top")

    for component in (left_component, right_component):
        axis.add_patch(
            Polygon(
                component,
                closed=True,
                facecolor=BLUE,
                edgecolor=BLUE,
                linewidth=1.6,
                alpha=0.22,
                zorder=4,
            )
        )

    for folded_component in (right_component_plus, left_component_plus):
        axis.add_patch(
            Polygon(
                folded_component,
                closed=True,
                facecolor="none",
                edgecolor=BLUE,
                linewidth=1.55,
                linestyle=(0, (4, 2.5)),
                zorder=7,
            )
        )

    for generator_component in (
        right_boundary_generators,
        left_boundary_generators,
    ):
        axis.add_patch(
            Polygon(
                generator_component,
                closed=True,
                facecolor="none",
                edgecolor=BLUE,
                linewidth=1.55,
                linestyle=(0, (1.2, 2.1)),
                zorder=7,
            )
        )

    axis.text(
        0.89,
        1.50,
        r"$K_+$",
        color=BLUE,
        ha="center",
        va="center",
        fontsize=12,
        zorder=9,
    )
    axis.text(
        -0.89,
        1.50,
        r"$-\overline{K_+}$",
        color=BLUE,
        ha="center",
        va="center",
        fontsize=10,
        zorder=9,
    )
    axis.text(
        -1.40,
        -0.18,
        r"$K$",
        color=BLUE,
        ha="center",
        va="center",
        fontsize=12,
        zorder=9,
    )
    axis.text(
        -1.40,
        0.18,
        r"$K_+$",
        color=BLUE,
        ha="center",
        va="center",
        fontsize=11,
        zorder=9,
    )
    axis.text(
        -0.50,
        2.45,
        r"$\mathcal{C}_K$",
        color=BLACK,
        ha="center",
        va="center",
        fontsize=13,
    )
    axis.set_title(
        r"(b) $\mathcal{C}_K="
        r"\operatorname{cone}(\{1,e^{\mathrm{i}\pi/3}\}"
        r"\cup(-\overline{K_+}))$"
    )


def main():
    plt.rcParams.update(
        {
            "font.family": "serif",
            "font.size": 11,
            "axes.titlesize": 11,
        }
    )
    figure, axes = plt.subplots(1, 2, figsize=(10.4, 4.45))
    draw_resolvent_cone(axes[0])
    draw_compact_profile_cone(axes[1])
    figure.subplots_adjust(left=0.025, right=0.985, bottom=0.06, top=0.90, wspace=0.16)
    figure.savefig(
        "resolvent_profile_cones.png",
        dpi=320,
        bbox_inches="tight",
    )
    figure.savefig(
        "resolvent_profile_cones.pdf",
        bbox_inches="tight",
    )
    plt.close(figure)


if __name__ == "__main__":
    main()
